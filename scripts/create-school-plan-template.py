"""Create SchoolDoc's own empty HWPX package with a separate Hancom instance.

No existing document or third-party template is opened. Run only on a Windows
development machine with Hancom installed; the browser does not use COM.
"""
from pathlib import Path
from tempfile import TemporaryDirectory
from zipfile import ZipFile, ZIP_STORED, ZIP_DEFLATED
import xml.etree.ElementTree as ET
import win32com.client

root = Path(__file__).resolve().parent.parent
target = root / "src/features/schoolDocuments/assets/blank-plan.hwpx"
target.parent.mkdir(parents=True, exist_ok=True)
with TemporaryDirectory(prefix="schooldoc-plan-") as temp:
    raw = Path(temp) / "blank.hwpx"
    hwp = win32com.client.DispatchEx("HWPFrame.HwpObject")
    try:
        hwp.XHwpWindows.Item(0).Visible = False
        hwp.RegisterModule("FilePathCheckDLL", "FilePathCheckerModule")
        hwp.SetMessageBoxMode(0x00020000)
        hwp.HAction.GetDefault("InsertText", hwp.HParameterSet.HInsertText.HSet)
        hwp.HParameterSet.HInsertText.Text = "SchoolDoc"
        hwp.HAction.Execute("InsertText", hwp.HParameterSet.HInsertText.HSet)
        if not hwp.SaveAs(str(raw), "HWPX", ""): raise RuntimeError("HWPX save failed")
    finally:
        hwp.Quit()
    with ZipFile(raw) as source:
        entries = {name: source.read(name) for name in source.namelist()
                   if name in {"mimetype", "version.xml", "META-INF/container.xml",
                               "META-INF/manifest.xml", "Contents/content.hpf",
                               "Contents/header.xml", "Contents/section0.xml",
                               "settings.xml"}}
    # Remove author, history, preview, and timestamps from the shipped empty file.
    content = ET.fromstring(entries["Contents/content.hpf"])
    for element in content.iter():
        if element.tag.split("}")[-1] == "metadata": element.clear()
        if element.tag.split("}")[-1] == "manifest":
            for child in list(element):
                href = child.attrib.get("href", "")
                if "Preview/" in href or "DocHistory/" in href or "Scripts/" in href: element.remove(child)
    entries["Contents/content.hpf"] = ET.tostring(content, encoding="utf-8", xml_declaration=True)
    # The package's schema/style definitions are generated by Hancom. The browser
    # replaces section0 entirely and writes only SchoolDoc-authored document data.
    with ZipFile(target, "w") as output:
        output.writestr("mimetype", entries.pop("mimetype"), compress_type=ZIP_STORED)
        for name, data in entries.items(): output.writestr(name, data, compress_type=ZIP_DEFLATED)
print(target)
