export function buildBehaviorAiRequest(input: BehaviorInput, model: string) {
  const { min, max } = commentLengthRange(input.length);
  const lengthInstruction = `이번 요청의 모든 학생은 공백·문장부호 포함 ${input.length}자를 목표로, 반드시 ${min}~${max}자 범위로 작성합니다. 메모 길이와 관계없이 선택한 특성과 메모의 의미를 충분히 풀어 쓰고, 없는 사건·실적·변화는 추가하지 않습니다.`;
  return {
    model, store: false, stream: true,
    instructions: `${behaviorInstruction}\n\n==이번 요청의 분량==\n${lengthInstruction}`,
    input: [{ role: 'user', content: [{ type: 'input_text', text: JSON.stringify(input) }] }],
    text: { format: { type: 'json_schema', name: 'neis_behavior', strict: true, schema: {
      type: 'object', additionalProperties: false, required: ['rows'], properties: {
        rows: { type: 'array', minItems: input.students.length, maxItems: input.students.length, items: {
          type: 'object', additionalProperties: false, required: ['id', 'text'], properties: {
            id: { type: 'string', enum: input.students.map((student) => student.id) }, text: { type: 'string' },
          },
        } },
      },
    } } },
  };
}
